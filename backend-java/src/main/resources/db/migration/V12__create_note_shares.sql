-- Notas compartilhadas para edição em conjunto.
-- O dono convida outra pessoa (que já tem conta) pelo e-mail; a convidada pode ler e editar
-- o texto daquela nota, ao vivo junto com o dono. A nota continua sendo do dono.
-- Apagar a nota apaga os convites (CASCADE).
CREATE TABLE note_shares (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    note_id    BIGINT NOT NULL REFERENCES notes (id) ON DELETE CASCADE,
    owner_id   BIGINT NOT NULL,
    user_id    BIGINT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT note_shares_unique UNIQUE (note_id, user_id)
);

CREATE INDEX note_shares_user_idx ON note_shares (user_id);
