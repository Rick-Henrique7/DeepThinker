-- Contas de usuário. Cada nota, mensagem do chat e configuração de IA
-- passa a ter um dono (user_id). Apagar a conta apaga os dados dela (CASCADE).
--
-- user_id fica opcional por um motivo: quem já usava o app tem dados sem dono.
-- A primeira conta criada herda esses dados (ver AuthService.adoptOrphanData).
CREATE TABLE users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR(100) NOT NULL,
    email         VARCHAR(255) NOT NULL,
    password_hash VARCHAR(100) NOT NULL,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT users_email_unique UNIQUE (email)
);

ALTER TABLE notes ADD COLUMN user_id BIGINT;
ALTER TABLE notes ADD CONSTRAINT notes_user_fk
    FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE;
CREATE INDEX notes_user_idx ON notes (user_id);

ALTER TABLE conversation_messages ADD COLUMN user_id BIGINT;
ALTER TABLE conversation_messages ADD CONSTRAINT conversation_messages_user_fk
    FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE;
CREATE INDEX conversation_messages_user_idx ON conversation_messages (user_id);

-- Cada pessoa tem as próprias chaves de IA: o par (provedor, chave) agora é único por usuário.
ALTER TABLE llm_settings ADD COLUMN user_id BIGINT;
ALTER TABLE llm_settings ADD CONSTRAINT llm_settings_user_fk
    FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE;
ALTER TABLE llm_settings DROP CONSTRAINT llm_settings_provider_key_unique;
ALTER TABLE llm_settings ADD CONSTRAINT llm_settings_user_provider_key_unique
    UNIQUE (user_id, provider, setting_key);
