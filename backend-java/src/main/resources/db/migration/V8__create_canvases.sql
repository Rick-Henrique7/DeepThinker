-- Canvas: um quadro infinito com cartões (texto, nota, link, grupo) e setas entre eles.
-- content guarda o desenho inteiro no formato aberto JSON Canvas (o mesmo do Obsidian):
-- dá para exportar um .canvas daqui e abrir no Obsidian, e o contrário também.
-- revision sobe a cada gravação. Se duas abas salvarem o mesmo canvas, a segunda recebe
-- 409 (conflito) em vez de apagar sem perceber o que a primeira fez.
-- cards = quantos cartões ele tem, para a lista não precisar abrir cada desenho.
CREATE TABLE canvases (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT NOT NULL,
    title      VARCHAR(255) NOT NULL,
    content    TEXT NOT NULL,
    cards      INTEGER NOT NULL DEFAULT 0,
    revision   BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX canvases_user_idx ON canvases (user_id, updated_at);
