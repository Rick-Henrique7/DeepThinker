-- Colunas do Quadro (Kanban) de cada pessoa, com nome e ordem próprios.
--
-- Um cartão é uma nota com a propriedade "status" igual ao nome da coluna. Nota sem "status"
-- não aparece no Quadro: só entra quem a pessoa mandou para lá. Renomear a coluna troca o status
-- das notas dela; excluir a coluna tira o status (as notas continuam existindo).
CREATE TABLE board_columns (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT NOT NULL,
    name       VARCHAR(60) NOT NULL,
    position   INT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT board_columns_name_unique UNIQUE (user_id, name)
);

CREATE INDEX board_columns_user_idx ON board_columns (user_id, position);
