-- Histórico de versões: cada linha é como a nota estava ANTES de uma mudança.
-- A versão atual é a própria nota (tabela notes); aqui ficam só as anteriores.
-- reason diz o que mudou a nota depois deste estado (edicao, propriedades, link, restauracao...).
-- Apagar a nota apaga o histórico dela (CASCADE).
CREATE TABLE note_versions (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    note_id    BIGINT NOT NULL REFERENCES notes (id) ON DELETE CASCADE,
    user_id    BIGINT NOT NULL,
    title      VARCHAR(255) NOT NULL,
    content    TEXT,
    reason     VARCHAR(32) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX note_versions_note_idx ON note_versions (note_id, id);
