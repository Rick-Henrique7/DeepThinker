-- Plugins da comunidade instalados por cada usuário.
--
-- O servidor só GUARDA o plugin (manifesto + código JavaScript como texto) e nunca o executa:
-- quem roda é o navegador da própria pessoa, isolado num iframe sem acesso ao app
-- (ver frontend/src/lib/plugins.ts). Cada usuário instala só para si.
--
-- permissions: lista separada por vírgula do que o plugin pode pedir (note:read, note:write, commands).
CREATE TABLE user_plugins (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT NOT NULL,
    plugin_key  VARCHAR(50) NOT NULL,
    name        VARCHAR(80) NOT NULL,
    version     VARCHAR(20) NOT NULL,
    description VARCHAR(300),
    author      VARCHAR(80),
    permissions VARCHAR(200) NOT NULL,
    code        TEXT NOT NULL,
    enabled     BOOLEAN NOT NULL,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT user_plugins_key_unique UNIQUE (user_id, plugin_key)
);
