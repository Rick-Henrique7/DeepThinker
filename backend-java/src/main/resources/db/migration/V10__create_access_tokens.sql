-- Tokens de acesso pessoal: o que uma IA de fora (Claude Desktop, Cursor...) usa para
-- entrar no servidor MCP (/mcp) em nome do usuário. Guardamos só o hash SHA-256:
-- o token inteiro aparece uma única vez, na hora de criar. Revogar = apagar a linha.
-- can_write: se a IA pode criar notas e mover cartões, ou só ler e navegar.
CREATE TABLE access_tokens (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      BIGINT NOT NULL,
    name         VARCHAR(80) NOT NULL,
    token_hash   VARCHAR(64) NOT NULL,
    prefix       VARCHAR(16) NOT NULL,
    can_write    BOOLEAN NOT NULL,
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    last_used_at TIMESTAMP WITH TIME ZONE,
    CONSTRAINT access_tokens_hash_unique UNIQUE (token_hash)
);

CREATE INDEX access_tokens_user_idx ON access_tokens (user_id);
