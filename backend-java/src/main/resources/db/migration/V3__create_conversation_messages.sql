-- Histórico do chat do Advogado do Diabo.
-- No Laravel o id da sessão ia escondido na coluna audio_url ("session:<id>");
-- aqui ele tem coluna própria e índice, o que deixa a busca por sessão rápida.
CREATE TABLE conversation_messages (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    note_id    BIGINT REFERENCES notes (id) ON DELETE SET NULL,
    session_id VARCHAR(64),
    role       VARCHAR(16) NOT NULL,
    content    TEXT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT conversation_messages_role_check CHECK (role IN ('user', 'assistant', 'system'))
);

CREATE INDEX conversation_messages_session_idx ON conversation_messages (session_id);
CREATE INDEX conversation_messages_note_idx ON conversation_messages (note_id);
