-- Configurações de IA editáveis pela tela, sem reiniciar o servidor.
-- Cada linha é (provedor, chave) -> valor. Ex.: (openai, api_key) -> "enc:...".
-- As colunas se chamam setting_key/setting_value porque "key" e "value"
-- são palavras reservadas em alguns bancos (como o H2).
CREATE TABLE llm_settings (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    provider      VARCHAR(32) NOT NULL,
    setting_key   VARCHAR(64) NOT NULL,
    setting_value TEXT,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT llm_settings_provider_key_unique UNIQUE (provider, setting_key)
);
