-- Arquivo original de cada documento importado (PDF, TXT ou MD). Com ele, o Leitor mostra o
-- documento do jeito que ele é (as páginas do PDF) e deixa grifar trechos.
--
-- Fica no próprio banco (BYTEA = bytes) e não numa pasta: assim a hospedagem continua sem
-- precisar de disco persistente nem de S3, e o backup do banco já leva os arquivos junto.
-- O upload já é limitado a 10 MB (application.yml). Apagar a nota apaga o arquivo (CASCADE).
CREATE TABLE document_files (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    note_id      BIGINT NOT NULL REFERENCES notes (id) ON DELETE CASCADE,
    user_id      BIGINT NOT NULL,
    filename     VARCHAR(255) NOT NULL,
    content_type VARCHAR(100) NOT NULL,
    size_bytes   BIGINT NOT NULL,
    data         BYTEA NOT NULL,
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT document_files_note_unique UNIQUE (note_id)
);

CREATE INDEX document_files_user_idx ON document_files (user_id);
