CREATE TABLE notes (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title       VARCHAR(255) NOT NULL UNIQUE,
    content     TEXT,
    summary     TEXT,
    source_type VARCHAR(32),
    source_meta TEXT,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at  TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX notes_source_type_idx ON notes (source_type);

CREATE TABLE connections (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_note_id BIGINT NOT NULL REFERENCES notes (id) ON DELETE CASCADE,
    target_note_id BIGINT NOT NULL REFERENCES notes (id) ON DELETE CASCADE,
    weight         DOUBLE PRECISION NOT NULL DEFAULT 1.0,
    created_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT connections_source_target_unique UNIQUE (source_note_id, target_note_id)
);
